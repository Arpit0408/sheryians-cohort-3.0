// Check whether an empty string is truthy or falsy.
const str = "";
if (str) {
  console.log("Truthy");
} else {
  console.log("Falsy");
}

// Check whether 0 is truthy or falsy.
const num = 0;

if (num) {
  console.log("Truthy");
} else {
  console.log("Falsy");
}

// Check whether [] is truthy or falsy.
const arr = [];

if (arr) {
  console.log("Truthy");
} else {
  console.log("Falsy");
}

// Create a variable and print "Valid" if it has a value otherwise print "Invalid".
const value = "Hello";

if (value) {
  console.log("Valid");
} else {
  console.log("Invalid");
}
